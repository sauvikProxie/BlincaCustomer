import { expect, test, type ConsoleMessage, type Page, type Request } from '@playwright/test';
import { publicRoutes, noindexRoutes } from '../src/lib/seo/routes.js';

/**
 * Every page a signed-out visitor can actually reach — the prerendered
 * marketing pages, the auth-flow pages, and a genuinely unknown URL for the
 * 404 — must load with a perfectly clean console and no failed network
 * request. No sign-in happens anywhere in this file, so it never touches
 * Better Auth's per-IP rate limit.
 *
 * Run this against both `bun run dev` and `bun run preview` (the production
 * build): Svelte's dev-mode checks (a11y hints, prop-type warnings) only run
 * under `vite dev` and are compiled out of the production bundle entirely, so
 * dev can surface real issues that a production-only run would miss, while
 * preview is what actually proves the deployed build is clean.
 *
 *   bun run dev     &  bunx playwright test e2e/console-clean.e2e.ts
 *   bun run preview &  CUSTOMER_BASE_URL=http://localhost:4173 \
 *                      bunx playwright test e2e/console-clean.e2e.ts
 */

const PUBLIC_PATHS = [...publicRoutes.map((r) => r.path), ...noindexRoutes];

type Violation = string;

function watch(page: Page, violations: Violation[]) {
	page.on('console', (msg: ConsoleMessage) => {
		const type = msg.type();
		if (type !== 'error' && type !== 'warning') return;
		// A dropped WebSocket during test teardown is Playwright closing the
		// page mid-flight, not an app bug.
		if (/WebSocket is closed before the connection/.test(msg.text())) return;
		violations.push(`console.${type}: ${msg.text()}`);
	});

	page.on('pageerror', (err) => {
		violations.push(`uncaught exception: ${err.message}`);
	});

	page.on('requestfailed', (req: Request) => {
		// Aborted-by-navigation is expected when a test moves on quickly;
		// anything else (DNS failure, refused connection, blocked request) is
		// a real problem.
		if (req.failure()?.errorText === 'net::ERR_ABORTED') return;
		violations.push(`request failed: ${req.method()} ${req.url()} — ${req.failure()?.errorText}`);
	});

	page.on('response', (res) => {
		if (res.status() >= 400) {
			violations.push(`${res.status()} response: ${res.request().method()} ${res.url()}`);
		}
	});
}

for (const path of PUBLIC_PATHS) {
	test(`${path} loads with a clean console and no failed requests`, async ({ page }) => {
		const violations: Violation[] = [];
		watch(page, violations);

		const response = await page.goto(path);
		expect(response?.ok(), `${path} should respond 2xx`).toBe(true);

		// Let the page finish hydrating and settle any async work (session
		// fetches on the auth pages, theme/locale toggles attaching handlers).
		await page.waitForLoadState('networkidle');

		expect(violations, violations.join('\n')).toEqual([]);
	});
}

test('an unknown URL 404s cleanly with no console or network errors', async ({ page }) => {
	const violations: Violation[] = [];
	watch(page, violations);

	const response = await page.goto('/this-page-does-not-exist-anywhere');
	expect(response?.status()).toBe(404);

	await page.waitForLoadState('networkidle');

	/*
	 * Two things are expected here, not bugs:
	 *  - the 404 response for the unknown URL itself;
	 *  - Chrome's own "Failed to load resource: ... 404" console.error, which
	 *    the browser logs for any top-level navigation that returns a non-2xx
	 *    status. It is generated by Chrome, not application code, and a
	 *    correct 404 page triggers it every time — there is nothing in the
	 *    page to fix.
	 * Anything else — a second failing request, an app-thrown error — is real.
	 */
	const unexpected = violations.filter(
		(v) =>
			!(v.includes('404 response') && v.includes('this-page-does-not-exist-anywhere')) &&
			!/console\.error: Failed to load resource: the server responded with a status of 404/.test(v)
	);
	expect(unexpected, unexpected.join('\n')).toEqual([]);
});
